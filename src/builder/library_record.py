# src/builder/library_record.py
"""
Structure records for the quantum-dot library.

Shared by the QD_builder library generator and the QDSpaceWebApp ingest so a
structure is described the same way whether it was generated by the builder
or added by hand: composition, centre species, size descriptors, a
rotation/translation-invariant fingerprint (to deduplicate and to match DFT
structures with their builder twins) and the record layout itself.
"""
from __future__ import annotations

import hashlib
from typing import Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

import numpy as np
from numpy.typing import NDArray

SCHEMA_VERSION = 1
CENTRE_TOL = 0.5  # Å: an atom this close to the core centroid defines the centre


def read_xyz_first_frame(path: str) -> Tuple[List[str], NDArray[np.float64]]:
    """Symbols and coordinates of the first frame of an XYZ file."""
    with open(path) as fh:
        n = int(fh.readline().split()[0])
        fh.readline()
        symbols: List[str] = []
        coords: List[List[float]] = []
        for _ in range(n):
            parts = fh.readline().split()
            symbols.append(parts[0])
            coords.append([float(x) for x in parts[1:4]])
    return symbols, np.asarray(coords, float)


def composition(symbols: Iterable[str]) -> Dict[str, int]:
    comp: Dict[str, int] = {}
    for s in symbols:
        comp[s] = comp.get(s, 0) + 1
    return comp


def formula(comp: Dict[str, int], order: Sequence[str] = ()) -> str:
    """Formula string with `order` elements first (e.g. Cd, Se), then the rest alphabetically."""
    head = [e for e in order if comp.get(e)]
    tail = sorted(e for e in comp if e not in head)
    return "".join(f"{e}{comp[e]}" for e in head + tail)


def total_charge(comp: Dict[str, int], charges: Dict[str, float]) -> Optional[int]:
    """Formal total charge, or None when an element has no known charge."""
    if any(e not in charges for e in comp):
        return None
    return int(round(sum(float(charges[e]) * n for e, n in comp.items())))


def _core(symbols: Sequence[str], pts: NDArray[np.float64], native: Iterable[str]) -> NDArray[np.float64]:
    native = set(native)
    mask = np.array([s in native for s in symbols])
    return pts[mask] if mask.any() else pts


def centre_species(
    symbols: Sequence[str],
    pts: NDArray[np.float64],
    native: Iterable[str],
    tol: float = CENTRE_TOL,
) -> Tuple[str, float]:
    """
    Species of the native atom at the core centroid, or "interstitial" when
    no native atom lies within `tol`.  Returns (label, distance in Å).
    """
    native = set(native)
    idx = [i for i, s in enumerate(symbols) if s in native]
    if not idx:
        return "unknown", float("nan")
    core = pts[idx]
    d = np.linalg.norm(core - core.mean(axis=0), axis=1)
    k = int(np.argmin(d))
    label = symbols[idx[k]] if d[k] <= tol else "interstitial"
    return label, float(d[k])


# Elements with about the solvent's electron density: invisible to SAXS unless
# native to the core (P in InP is seen, P in a phosphonate is not).
ORGANIC_ELEMENTS = frozenset({"H", "B", "C", "N", "O", "F", "Si", "P"})

_ELEMENTS = (
    "H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni Cu Zn Ga Ge As Se Br Kr "
    "Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb Te I Xe Cs Ba La Ce Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm Yb "
    "Lu Hf Ta W Re Os Ir Pt Au Hg Tl Pb Bi Po At Rn"
).split()
_Z = {e: i + 1 for i, e in enumerate(_ELEMENTS)}


def bulk_volume_per_atom(cif_path: str) -> Dict[str, float]:
    """Volume per atom (Å^3) of the bulk crystal in `cif_path`, keyed by each of its elements."""
    from pymatgen.core import Structure
    st = Structure.from_file(str(cif_path))
    v = float(st.volume) / len(st)
    return {el.symbol: v for el in st.composition.elements}


def _sphere_form_factor(q: NDArray[np.float64], radius: float) -> NDArray[np.float64]:
    x = np.maximum(q * radius, 1e-8)
    return (3.0 * (np.sin(x) - x * np.cos(x)) / x ** 3) ** 2


def debye_intensity(pts: NDArray[np.float64], weights: NDArray[np.float64], q: NDArray[np.float64],
                    bin_width: float = 0.02) -> NDArray[np.float64]:
    """Debye intensity sum_ij w_i w_j sin(q r_ij)/(q r_ij) from a histogram of pair distances."""
    from scipy.spatial.distance import cdist
    r_max = 2.0 * float(np.linalg.norm(pts - pts.mean(axis=0), axis=1).max()) + 2.0 * bin_width
    n_bins = int(r_max / bin_width) + 2
    hist = np.zeros(n_bins)
    block = max(1, int(2e7 // len(pts)))
    for i0 in range(0, len(pts), block):
        idx = (cdist(pts[i0:i0 + block], pts) / bin_width).astype(np.int64).ravel()
        w = (weights[i0:i0 + block, None] * weights[None, :]).ravel()
        hist += np.bincount(idx, weights=w, minlength=n_bins)[:n_bins]
    centres = (np.arange(n_bins) + 0.5) * bin_width
    return (hist[None, :] * np.sinc(np.outer(q, centres) / np.pi)).sum(axis=1)


def size_descriptors(
    symbols: Sequence[str],
    pts: NDArray[np.float64],
    native: Iterable[str],
    bulk_volume: Optional[Mapping[str, float]] = None,
) -> Dict[str, object]:
    """
    Size descriptors in nm, defined as an experiment would measure them.

    d_nm          SAXS diameter, the library's filter value: the homogeneous
                  sphere fitted to the first lobe of the Debye intensity of
                  the SAXS-visible atoms (core plus inorganic shell such as
                  halides; organics match the solvent and are invisible),
                  each weighted by its atomic number.
    d_volume_nm   diameter of the sphere holding the core atoms at bulk
                  density (`bulk_volume`: Å^3 per atom by element, see
                  `bulk_volume_per_atom`); compares with sizes from elemental
                  analysis.  None without `bulk_volume`.
    axes_nm       diameters of the homogeneous ellipsoid with the same
                  electron-density gyration tensor, longest first.
    aspect_ratio  longest / shortest of `axes_nm` (1 for spheres and cubes).
    d_max_nm      largest core-atom distance from the core centroid, doubled.
    d_hull_nm     diameter of the sphere with the core convex-hull volume.
    """
    native = set(native)
    syms = list(symbols)
    pts = np.asarray(pts, float)
    is_core = np.array([s in native for s in syms])
    core = pts[is_core] if is_core.any() else pts
    out: Dict[str, object] = {"n_core": int(is_core.sum())}
    empty = {"d_nm": 0.0, "d_volume_nm": None, "axes_nm": [0.0, 0.0, 0.0], "aspect_ratio": 1.0,
             "d_max_nm": 0.0, "d_hull_nm": 0.0}
    visible = np.array([s in native or s not in ORGANIC_ELEMENTS for s in syms])
    if len(core) < 2 or visible.sum() < 2:
        return {**out, **empty}

    # SAXS: atomic-number-weighted electron density of the visible atoms.
    r = pts[visible]
    z = np.array([_Z.get(s, 20) for s, v in zip(syms, visible) if v], float)
    r = r - (z[:, None] * r).sum(axis=0) / z.sum()
    gyr = (z[:, None, None] * r[:, :, None] * r[:, None, :]).sum(axis=0) / z.sum()
    lam = np.clip(np.sort(np.linalg.eigvalsh(gyr))[::-1], 0.0, None)
    axes = 2.0 * np.sqrt(5.0 * lam)                      # uniform ellipsoid: <x^2> = a^2 / 5
    r0 = max(np.sqrt(5.0 / 3.0 * lam.sum()), 1.0)        # Guinier radius, start of the fit
    q = np.linspace(0.01, 1.3 * 4.493 / r0, 240)         # first lobe and ~30% beyond its minimum
    intensity = np.abs(debye_intensity(r, z, q)) + 1e-30
    from scipy.optimize import least_squares
    fit = least_squares(
        lambda p: np.log(p[0] * _sphere_form_factor(q, p[1]) + 1e-30) - np.log(intensity),
        [intensity[0], r0], bounds=([0.0, 0.5], [np.inf, 10.0 * r0 + 10.0]),
    )
    out["d_nm"] = round(2.0 * float(fit.x[1]) / 10.0, 3)

    out["d_volume_nm"] = None
    core_syms = [s for s, c in zip(syms, is_core) if c]
    if bulk_volume and all(s in bulk_volume for s in core_syms):
        vol = sum(float(bulk_volume[s]) for s in core_syms)
        out["d_volume_nm"] = round(2.0 * (3.0 * vol / (4.0 * np.pi)) ** (1.0 / 3.0) / 10.0, 3)

    out["axes_nm"] = [round(float(a) / 10.0, 3) for a in axes]
    out["aspect_ratio"] = round(float(axes[0] / axes[2]), 3) if axes[2] > 0 else None

    cen = core.mean(axis=0)
    out["d_max_nm"] = round(2.0 * float(np.linalg.norm(core - cen, axis=1).max()) / 10.0, 3)
    try:
        from scipy.spatial import ConvexHull
        vol = ConvexHull(core).volume
        out["d_hull_nm"] = round(2.0 * (3.0 * vol / (4.0 * np.pi)) ** (1.0 / 3.0) / 10.0, 3)
    except Exception:
        out["d_hull_nm"] = None
    return out


def fingerprint(symbols: Sequence[str], pts: NDArray[np.float64], resolution: float = 0.05) -> str:
    """
    Rotation- and translation-invariant structure hash: composition plus the
    per-species sorted distances to the centroid, binned to `resolution` Å.
    Identical builder outputs (e.g. two sizes producing the same cluster)
    share a fingerprint; relaxed geometries generally do not.
    """
    pts = np.asarray(pts, float)
    cen = pts.mean(axis=0)
    parts = []
    for s in sorted(set(symbols)):
        d = np.linalg.norm(pts[[i for i, x in enumerate(symbols) if x == s]] - cen, axis=1)
        bins = np.round(np.sort(d) / resolution).astype(int)
        parts.append(s + ":" + ",".join(map(str, bins)))
    return hashlib.sha1("|".join(parts).encode()).hexdigest()[:16]


def radial_signature(symbols: Sequence[str], pts: NDArray[np.float64]) -> Dict[str, NDArray[np.float64]]:
    """Per-species sorted distances to the centroid (rotation/translation invariant)."""
    pts = np.asarray(pts, float)
    cen = pts.mean(axis=0)
    return {
        s: np.sort(np.linalg.norm(pts[[i for i, x in enumerate(symbols) if x == s]] - cen, axis=1))
        for s in sorted(set(symbols))
    }


def signature_distance(a: Dict[str, NDArray[np.float64]], b: Dict[str, NDArray[np.float64]]) -> float:
    """
    Mean absolute difference (Å) between two radial signatures; infinite when
    the compositions differ.  Tolerant to small perturbations or relaxation,
    unlike `fingerprint`: used to link a DFT structure to its builder twin.
    """
    if set(a) != set(b) or any(len(a[s]) != len(b[s]) for s in a):
        return float("inf")
    diffs = np.concatenate([np.abs(a[s] - b[s]) for s in a])
    return float(diffs.mean()) if len(diffs) else 0.0


def min_distance(pts: NDArray[np.float64]) -> float:
    from scipy.spatial import cKDTree
    if len(pts) < 2:
        return float("inf")
    d, _ = cKDTree(pts).query(pts, k=2)
    return float(d[:, 1].min())


def structure_id(material: str, centre: str, formula_str: str, surface: str) -> str:
    return f"{material}-{centre}-{formula_str}-{surface}"


def describe_structure(
    symbols: Sequence[str],
    pts: NDArray[np.float64],
    *,
    native_order: Sequence[str],
    charges: Dict[str, float],
    centre_index: Optional[int] = None,
    bulk_volume: Optional[Mapping[str, float]] = None,
) -> dict:
    """
    Everything computable from coordinates alone (the core of a record).

    `centre_index` names the atom the cut was centred on, when known (builder
    output).  Polar sites such as wurtzite's leave the core centroid up to ~1 Å
    off that atom along c, beyond what `centre_species` can attribute.
    `bulk_volume` (Å^3 per atom by element) enables the volume diameter.
    """
    comp = composition(symbols)
    native = set(native_order)
    if centre_index is None:
        centre, centre_d = centre_species(symbols, pts, native)
    else:
        centre = symbols[centre_index]
        centre_d = float(np.linalg.norm(pts[centre_index] - _core(symbols, pts, native).mean(axis=0)))
    return {
        "formula": formula(comp, native_order),
        "composition": comp,
        "core": {e: n for e, n in comp.items() if e in native},
        "ligands": {e: n for e, n in comp.items() if e not in native},
        "n_atoms": int(len(symbols)),
        "total_charge": total_charge(comp, charges),
        "centre": centre,
        "centre_offset_A": round(centre_d, 3),
        "size": size_descriptors(symbols, pts, native, bulk_volume),
        "fingerprint": fingerprint(symbols, pts),
    }


def make_record(
    *,
    material: str,
    family: str,
    phase: str,
    surface: str,
    source: str,
    description: dict,
    stages: List[dict],
    origin: Optional[dict] = None,
    extra: Optional[dict] = None,
) -> dict:
    """Assemble a library record (schema_version 1)."""
    rec = {
        "schema_version": SCHEMA_VERSION,
        "id": structure_id(material, description["centre"], description["formula"], surface),
        "material": material,
        "family": family,
        "phase": phase,
        "surface": surface,
        "source": source,
        **description,
        "stages": stages,
        "origin": origin or {},
    }
    if extra:
        rec.update(extra)
    return rec
